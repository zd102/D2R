import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

// Reproducible original data; D2R adjustments belong in expansion-skills.ts.
const commit = 'e67aa992be5db412bd0437bb8afb95eedee0c9bc';
const classes = { nec: 'necromancer', bar: 'barbarian', dru: 'druid', ass: 'assassin' };
async function table(name) {
  let source;
  if (process.argv[2]) source = await readFile(join(process.argv[2], `d2r-expansion-${name}.txt`), 'utf8');
  else {
    const response = await fetch(`https://raw.githubusercontent.com/fabd/diablo2/${commit}/code/d2_113_data/${name}.txt`);
    if (!response.ok) throw new Error(`${name}: ${response.status}`);
    source = await response.text();
  }
  const rows = source.split(/\r?\n/).map(line => line.split('\t')), headers = rows.shift();
  return rows.map(row => Object.fromEntries(headers.flatMap((key, i) => headers.indexOf(key)===i?[[key, row[i] ?? '']]:[])));
}
const [skills, descriptions] = await Promise.all([table('Skills'), table('SkillDesc')]);
const existing = await readFile(new URL('../src/item-skill-definitions.ts', import.meta.url), 'utf8');
const aliases = new Map([...existing.matchAll(/\['(\w+)',(\d+),/g)].map(([, id, number]) => [number, id]));
for (const [number, id] of Object.entries({94:'fireGolem',231:'carrionVine',241:'solarCreeper',251:'fireBlast',256:'shockWeb',258:'burstOfSpeed',259:'fistsOfFire',262:'wakeOfFire',269:'clawsOfThunder',272:'wakeOfInferno',274:'bladesOfIce',280:'phoenixStrike'})) aliases.set(number,id);
const skillId = row => aliases.get(row.Id) ?? row.skill.split(' ').map((word, i) => i ? word : word.toLowerCase()).join('');
const ids = new Map(skills.map(row => [row.skill, skillId(row)]));
const records = skills.filter(row => classes[row.charclass]).map(row => {
  const n = key => Number(row[key]) || 0, desc = descriptions.find(desc => desc.skilldesc === row.skilldesc);
  return [skillId(row), { number: n('Id'), name: row.skill, classId: classes[row.charclass], level: n('reqlevel'),
    page: Number(desc?.SkillPage) || Number(desc?.skillpage) || 1, column: Number(desc?.SkillColumn) || Number(desc?.skillcolumn) || 1,
    requires: [row.reqskill1, row.reqskill2, row.reqskill3].filter(Boolean).map(name => ids.get(name)),
    element: row.EType, shift: n('HitShift'), min: ['EMin', ...[1,2,3,4,5].map(i => `EMinLev${i}`)].map(n), max: ['EMax', ...[1,2,3,4,5].map(i => `EMaxLev${i}`)].map(n),
    physicalMin: ['MinDam', ...[1,2,3,4,5].map(i => `MinLevDam${i}`)].map(n), physicalMax: ['MaxDam', ...[1,2,3,4,5].map(i => `MaxLevDam${i}`)].map(n),
    mana: n('mana'), manaStep: n('lvlmana'), manaShift: n('manashift'), minMana: n('minmana'),
    length: ['ELen','ELevLen1','ELevLen2','ELevLen3'].map(n), params: [1,2,3,4,5,6,7,8].map(i => n(`Param${i}`)),
    synergy: row.EDmgSymPerCalc, physicalSynergy: row.DmgSymPerCalc,
    calcs: [row.calc1,row.calc2,row.calc3,row.calc4], paramNames: [1,2,3,4,5,6,7,8].map(i => row[`*Param${i} Description`] || row[`Param${i} Description`] || ''),
  }];
});
if (records.length !== 120) throw new Error(`Expected 120 skills, got ${records.length}`);
await writeFile(new URL('../src/expansion-skill-data.ts', import.meta.url), `// Generated by scripts/import-expansion-skills.mjs; LoD 1.13 ${commit}.\n// D2R changes are applied separately; original numbers and prerequisite IDs remain stable.\nexport const EXPANSION_SKILL_DATA = {\n${records.map(([id,row]) => `  ${JSON.stringify(id)}: ${JSON.stringify(row)},`).join('\n')}\n};\nexport type ExpansionSkillId = keyof typeof EXPANSION_SKILL_DATA;\n`);
console.log(records.map(([id,row]) => `${row.number} ${id} ${row.classId} page=${row.page} column=${row.column}`).join('\n'));
const [weapons, armor] = await Promise.all([table('Weapons'),table('Armor')]);
const oneHanded = Object.fromEntries(weapons.filter(row=>row.type==='swor'&&row['2handed']==='1').map(row=>[row.code,[Number(row.mindam),Number(row.maxdam)]]));
const kicks = Object.fromEntries(armor.filter(row=>row.type==='boot').map(row=>[row.code,[Number(row.mindam),Number(row.maxdam)]]));
await writeFile(new URL('../src/expansion-equipment-data.ts',import.meta.url),`// Generated from LoD 1.13 Weapons.txt / Armor.txt (${commit}).\nexport const ONE_HANDED_SWORDS:Record<string,number[]> = ${JSON.stringify(oneHanded)};\nexport const BOOT_KICKS:Record<string,number[]> = ${JSON.stringify(kicks)};\n`);
